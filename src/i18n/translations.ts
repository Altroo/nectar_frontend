type TranslationValue = string | readonly TranslationValue[] | { readonly [key: string]: TranslationValue };

export const isLanguageCode = (value: string | null | undefined): value is LanguageCode => Boolean(value && languages.some((language) => language.code === value));

export const languageDirection = (language: LanguageCode) => languages.find((item) => item.code === language)?.dir ?? 'ltr';

const nestedValue = (source: TranslationValue, key: string): TranslationValue | undefined =>
	key.split('.').reduce<TranslationValue | undefined>((value, part) => {
		if (!value || typeof value !== 'object') return undefined;
		if (Array.isArray(value)) return value[Number(part)];
		return (value as { readonly [key: string]: TranslationValue })[part];
	}, source);

const interpolate = (value: string, params?: Record<string, string | number>) => {
	if (!params) return value;
	return Object.entries(params).reduce((result, [key, replacement]) => result.replaceAll(`{${key}}`, String(replacement)), value);
};

export const translate = (language: LanguageCode, key: string, fallback = '', params?: Record<string, string | number>) => {
	const value = nestedValue(translations[language] as TranslationValue, key) ?? nestedValue(translations[defaultLanguage] as TranslationValue, key);
	return typeof value === 'string' ? interpolate(value, params) : fallback;
};

const localizedTuple = (items: Record<LanguageCode, Record<string, readonly unknown[]>>, language: LanguageCode, key: string) => items[language][key] ?? items[defaultLanguage][key];

export const localizeGuidePlace = (language: LanguageCode, place: GuidePlace): GuidePlace => {
	const localized = localizedTuple(guidePlaces, language, place.title);
	if (!localized) return place;
	return { ...place, title: String(localized[0]), description: String(localized[1]) };
};

export const localizeEventIdea = (language: LanguageCode, idea: EventIdea): EventIdea => {
	const localized = localizedTuple(eventIdeas, language, idea.category);
	if (!localized) return idea;
	return {
		...idea,
		category: String(localized[0]),
		title: String(localized[1]),
		description: String(localized[2]),
		bullet_points: Array.isArray(localized[3]) ? localized[3].map(String) : idea.bullet_points,
	};
};

