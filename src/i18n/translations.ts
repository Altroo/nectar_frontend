export const localizePurplePlan = (language: LanguageCode, plan: PurplePearlPlan): PurplePearlPlan => {
	const localized = purplePlanTitles[language][plan.key];
	const plan3dLabel = translations[language].purple.planLabels.plan3d;
	const secondary3dLabel = translations[language].purple.planLabels.secondary3d;
	return {
		...plan,
		button_label: localized?.button ?? plan.button_label,
		title: localized?.title ?? plan.title,
		description: localized?.description ?? plan.description,
		image_3d_title: localized?.image3dTitle ?? plan3dLabel,
		image_3d_secondary_title: localized?.image3dSecondaryTitle ?? secondary3dLabel,
	};
};
